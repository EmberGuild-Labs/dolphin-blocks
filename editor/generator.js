/* ======================= Logic (built-ins) ======================= */
G.forBlock["controls_if"] = function (block) {
    let n = 0;
    let code = "";
    do {
        const cond = G.valueOr(block, "IF" + n, G.ORDER_NONE, "false");
        const branch = G.statementToCode(block, "DO" + n);
        code += (n === 0 ? "    if (" : " else if (") + cond + ") {\n" + branch + "    }";
        n++;
    } while (block.getInput("IF" + n));
    if (block.getInput("ELSE")) {
        const branch = G.statementToCode(block, "ELSE");
        code += " else {\n" + branch + "    }";
    }
    return code + "\n";
};

G.forBlock["logic_compare"] = function (block) {
    const ops = { EQ: "==", NEQ: "!=", LT: "<", LTE: "<=", GT: ">", GTE: ">=" };
    const op = ops[block.getFieldValue("OP")];
    const order = op === "==" || op === "!=" ? G.ORDER_EQUALITY : G.ORDER_RELATIONAL;
    const a = G.valueOr(block, "A", order, "0");
    const b = G.valueOr(block, "B", order, "0");
    return [a + " " + op + " " + b, order];
};

G.forBlock["logic_operation"] = function (block) {
    const op = block.getFieldValue("OP") === "AND" ? "&&" : "||";
    const order = op === "&&" ? G.ORDER_AND : G.ORDER_OR;
    const a = G.valueOr(block, "A", order, "false");
    const b = G.valueOr(block, "B", order, "false");
    return [a + " " + op + " " + b, order];
};

G.forBlock["logic_negate"] = function (block) {
    const a = G.valueOr(block, "BOOL", G.ORDER_UNARY, "false");
    return ["!(" + a + ")", G.ORDER_UNARY];
};

G.forBlock["logic_boolean"] = function (block) {
    return [block.getFieldValue("BOOL") === "TRUE" ? "true" : "false", G.ORDER_ATOMIC];
};

