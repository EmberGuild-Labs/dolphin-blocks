// Print accepts text or a number; pick the right runtime call from the plugged block.
function outputType(block, inputName) {
    const t = block.getInputTargetBlock(inputName);
    if (!t || !t.outputConnection) return null;
    const checks = t.outputConnection.getCheck();
    if (!checks) return null;
    if (checks.includes("Number")) return "Number";
    if (checks.includes("String")) return "String";
    return null;
}

G.forBlock["db_print_text"] = function (block) {
    const kind = outputType(block, "TEXT");
    if (kind === "Number") {
        const val = G.valueOr(block, "TEXT", G.ORDER_NONE, "0");
        return "    db_print_num(ctx, \"\", (float)(" + val + "));\n";
    }
    const val = G.valueOr(block, "TEXT", G.ORDER_NONE, '""');
    return "    db_print(ctx, " + val + ");\n";
};
