// Dolphin Blocks — C code generator for the Flipper Zero runtime (dolphin_blocks.h).
// A fresh Blockly.Generator has no block handlers, so every block used in the
// toolbox — including the reused built-ins — is implemented here.

const dolphinC = new Blockly.Generator("DolphinC");

// Operator precedence (higher binds tighter is lower number here).
dolphinC.ORDER_ATOMIC = 0;
dolphinC.ORDER_UNARY = 1;
dolphinC.ORDER_MUL = 2;
dolphinC.ORDER_ADD = 3;
dolphinC.ORDER_RELATIONAL = 4;
dolphinC.ORDER_EQUALITY = 5;
dolphinC.ORDER_AND = 6;
dolphinC.ORDER_OR = 7;
dolphinC.ORDER_NONE = 99;

dolphinC.appName = "My Flipper App";

dolphinC.init = function (workspace) {
    this.numVars_ = Object.create(null); // cid -> true
    this.txtVars_ = Object.create(null);
    this.loopDepth_ = 0;
    this.nameDB_ = Object.create(null);
};

// Make a safe C identifier from a user-typed variable name.
function dbCid(prefix, raw) {
    let s = String(raw == null ? "" : raw).trim().replace(/[^A-Za-z0-9_]/g, "_");
    if (!s) s = "x";
    if (/^[0-9]/.test(s)) s = "_" + s;
    return prefix + s;
}

dolphinC.escapeC = function (str) {
    return String(str == null ? "" : str)
        .replace(/\\/g, "\\\\")
        .replace(/"/g, '\\"')
        .replace(/\n/g, "\\n")
        .replace(/\r/g, "\\r")
        .replace(/\t/g, "\\t");
};

dolphinC.valueOr = function (block, name, order, fallback) {
    const code = this.valueToCode(block, name, order);
    return code && code.length ? code : fallback;
};

// Chain statements (and keep it responsive to Back inside loops is handled per-loop).
dolphinC.scrub_ = function (block, code, thisOnly) {
    const next = block.nextConnection && block.nextConnection.targetBlock();
    let nextCode = "";
    if (next && !thisOnly) nextCode = this.blockToCode(next);
    return code + nextCode;
};

dolphinC.finish = function (code) {
    const numDecls = Object.keys(this.numVars_).sort().map((v) => `    float ${v} = 0;`);
    const txtDecls = Object.keys(this.txtVars_).sort().map((v) => `    char ${v}[64] = "";`);
    const decls = numDecls.concat(txtDecls);

    let out = "";
    out += "// Generated by Dolphin Blocks — do not edit by hand.\n";
    out += '#include "dolphin_blocks.h"\n';
    out += "#include <math.h>\n\n";
    out += `const char* DOLPHIN_APP_NAME = "${this.escapeC(this.appName)}";\n\n`;
    out += "void dolphin_program(DbCtx* ctx) {\n";
    if (decls.length) out += decls.join("\n") + "\n\n";
    if (decls.length === 0 && !code.trim()) out += "    db_print(ctx, \"Empty program\");\n";
    out += code;
    out += "    (void)ctx;\n";
    out += "}\n";
    return out;
};

