#!/usr/bin/env python3
"""Bundle the runtime C sources into editor/runtime_sources.js.

The editor embeds the runtime so Export works with no network/fetch — which lets
the packaged macOS app run entirely from file://. Re-run this whenever anything
in runtime/ changes.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RUNTIME = os.path.join(ROOT, "runtime")
OUT = os.path.join(ROOT, "editor", "runtime_sources.js")

FILES = [
    "dolphin_blocks.h",
    "dolphin_blocks_priv.h",
    "dolphin_blocks.c",
    "db_ir.c",
    "db_subghz.c",
    "db_nfc.c",
    "db_ble.c",
    "db_uart.c",
    "db_file.c",
]

def main():
    data = {}
    for name in FILES:
        with open(os.path.join(RUNTIME, name), "r", encoding="utf-8") as f:
            data[name] = f.read()
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/bundle_runtime.py — do not edit by hand.\n")
        f.write("// Embeds the Flipper runtime so Export works offline (no fetch).\n")
        f.write("window.DOLPHIN_RUNTIME = ")
        f.write(json.dumps(data, ensure_ascii=False, indent=0))
        f.write(";\n")
    print("Wrote", OUT, "with", len(FILES), "files")

if __name__ == "__main__":
    main()
